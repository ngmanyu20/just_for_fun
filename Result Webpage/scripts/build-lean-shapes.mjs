/**
 * build-lean-shapes.mjs -- generates the "join-only" shape CSVs the data
 * layer uses for pages that never render a map (the election overview, seat
 * lists, referendum authority/county rollups -- see election-site/js/data/
 * shapes.js's getShapeJoinIndex()).
 *
 * Why this exists: shapes/df_polygon.csv, df_county.csv and
 * df_constituency.csv carry a `geometry` (WKT polygon) and `centroid` column
 * that dominates their file size (df_polygon.csv alone is ~8MB, almost
 * entirely geometry text) even though most pages only need the plain join
 * columns (Shape_ID, Constituency, District, ...) to group results -- not
 * the shape to draw. Map-rendering pages still read the original,
 * unmodified files (via shapes.js's getShapeIndex()) and are untouched by
 * this script.
 *
 * Run this any time the source shapes/*.csv files change (they're
 * regenerated by the notebooks under shapefile/). It's also wired up as this
 * site's Render build command (see render.yaml) so a fresh deploy always
 * regenerates the lean files from whatever shapes/*.csv landed in that
 * commit, instead of relying on someone remembering to run it and commit the
 * output.
 *
 * Node, not Python (an earlier version of this script was
 * scripts/build_lean_shapes.py -- switched after Render's static-site build
 * environment 404'd on the generated files, most likely because that build
 * image doesn't guarantee a `python`/`python3` interpreter the way it
 * guarantees Node for a static site's build step). Zero dependencies --
 * plain `node scripts/build-lean-shapes.mjs` needs no package.json (a
 * `.mjs` file is always ES module regardless), and reuses the exact same
 * `parseCSV` the browser data layer uses (election-site/js/data/csv.js is a
 * pure function with no fetch/DOM dependency, safe to import straight into
 * Node -- see that file's own doc comment).
 */

import { readFileSync, writeFileSync, existsSync, statSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import path from 'node:path';
import { parseCSV } from '../election-site/js/data/csv.js';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const DATA_ROOT = path.resolve(__dirname, '..', 'data');

// (source file, output file) -- output gets every column from the source
// EXCEPT `geometry`/`centroid`. Only files actually read by the join-only
// code path (shapes.js's getShapeJoinIndex()) need a lean counterpart.
const SOURCES = [
  ['shapes/df_polygon.csv', 'shapes/df_polygon_lean.csv'],
  ['shapes/df_county.csv', 'shapes/df_county_lean.csv'],
  ['shapes/df_constituency.csv', 'shapes/df_constituency_lean.csv'],
];

const DROP_COLUMNS = new Set(['geometry', 'centroid']);

/** Quote a field only if it needs it (RFC4180), matching csv.js's parser on the way back out. */
function csvField(value) {
  const s = value == null ? '' : String(value);
  return /[",\r\n]/.test(s) ? `"${s.replace(/"/g, '""')}"` : s;
}

function buildLeanCsv(srcRel, destRel) {
  const src = path.join(DATA_ROOT, srcRel);
  const dest = path.join(DATA_ROOT, destRel);
  if (!existsSync(src)) throw new Error(`build-lean-shapes: source file missing: ${src}`);

  const rows = parseCSV(readFileSync(src, 'utf-8'));
  if (rows.length === 0) {
    writeFileSync(dest, '');
    console.log(`  ${srcRel} -> ${destRel}: 0 rows (empty source)`);
    return;
  }

  const keepColumns = Object.keys(rows[0]).filter((col) => !DROP_COLUMNS.has(col));
  const lines = [keepColumns.map(csvField).join(',')];
  for (const row of rows) {
    lines.push(keepColumns.map((col) => csvField(row[col])).join(','));
  }
  writeFileSync(dest, lines.join('\r\n') + '\r\n');

  const srcSize = statSync(src).size;
  const destSize = statSync(dest).size;
  const savedPct = srcSize ? 100 * (1 - destSize / srcSize) : 0;
  console.log(
    `  ${srcRel} -> ${destRel}: ${rows.length} rows, ` +
      `${(srcSize / 1024).toFixed(0)}KB -> ${(destSize / 1024).toFixed(0)}KB (${savedPct.toFixed(0)}% smaller)`
  );
}

function main() {
  console.log(`build-lean-shapes: data root = ${DATA_ROOT}`);
  for (const [srcRel, destRel] of SOURCES) {
    buildLeanCsv(srcRel, destRel);
  }
  console.log('build-lean-shapes: done');
}

main();
